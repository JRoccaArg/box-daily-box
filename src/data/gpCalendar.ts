// Calendario de temporadas de F1, usado por el juego "Team Radio" para
// generar las 5 opciones falsas de cada radio (mismo circuito en otro año,
// otro GP de la misma temporada, mismo GP en una temporada lejana).
//
// A diferencia de src/data/teamRadios.ts, este dataset NO pasó por
// verificación con búsquedas web (decisión de Etapa 3): son calendarios de
// carreras, un dato público y estable, distinto de una frase citada textual
