// de teamRadios.ts, ese sí verificado), solo la lista de opciones falsas.
//
// Cobertura: 1996-2026. En teoría solo hacían falta los años de las radios
// ±2 (para la opción "mismo circuito, año siguiente/anterior"), pero como
// las radios cubren casi todos los años de ese rango sin huecos grandes, el
// cálculo real terminó siendo el rango completo igual.
//
// Mismas convenciones de nombre que gpResults.ts: `g` = nombre oficial del
// GP ese año (algunos cambian de nombre con el tiempo, ej. "Brazilian Grand
// Prix" hasta 2020 -> "São Paulo Grand Prix" desde 2021), `c` = nombre corto
// y reconocible del circuito (ciudad o nombre de trazado, el que sea más
// identificable).

